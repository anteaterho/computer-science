# 학습 목표: 1부터 입력받은 수까지의 합 구하기 — for + range로 누적하기

'''
100이하의 양의 정수만 입력된다.
for 문을 이용하여 1부터 입력받은 정수까지의 합을 구하여 출력하는 프로그램을 작성하라.
'''

a = int(input())

if a > 0 and a < 100:
    for i in range(a):
        a = a + i

    print(a)



